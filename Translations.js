function t(key, language, values) {
  var code = String(language || "").toLowerCase().replace("_", "-");
  var catalog = code === "pt" || code === "pt-pt" ? ptPT : en;
  var result = catalog[key] !== undefined ? catalog[key] : (en[key] !== undefined ? en[key] : String(key));
  if (values !== undefined && values !== null) {
    var args = Array.isArray(values) ? values : [values];
    for (var i = 0; i < args.length; i++)
      result = result.replace("%" + (i + 1), String(args[i]));
  }
  return result;
}

// Display-only translation for known messages produced by the service.
// Keep the original message for unknown backend errors (including commands,
// file paths and diagnostics), and do not modify service state or logs.
var serviceMessages = {};
for (var key in en) {
  if (key.indexOf("service.") === 0)
    serviceMessages[en[key]] = key;
}

function message(raw, language) {
  if (raw === undefined || raw === null) return "";
  var source = String(raw);
  var key = serviceMessages[source];
  return key !== undefined ? t(key, language) : source;
}
